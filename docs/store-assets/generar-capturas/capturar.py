"""Per-scene navigation for Constanza's Play Store screenshots.

Scene order and numbering follow docs/play-store-publication-texts.md's "Capturas — Orden
recomendado" table exactly — 1 Today, 2 notification, 3 habit editor, 4 colour picker, 5 habit
list, 6 settings, 7 progress. Progress sits last deliberately: it is real, honest UI (three lines
of text, nothing to fake), not a hero shot, so it does not compete for the two above-the-fold slots
Play shows without scrolling.

Every scene function that ends mid-navigation returns the app to a KNOWN screen before the next
one starts — usually by relaunching outright (`force_stop` + `start_app`) rather than trusting a
chain of back presses. That is not caution for its own sake: a full pass measured live that a
single back press from Progress exits straight past Today to the launcher, and a single back press
from Settings does too — the back stack this app builds when a screen is reached through Habit
List's overflow menu does not shrink one level at a time the way it looks like it should.
"""

